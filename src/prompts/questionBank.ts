  "你喜欢什么小动物呀？",
  "你喜欢画画吗？最喜欢画什么呀？",
  "如果你有一支魔法棒，你想变出什么呀？",
  "你最喜欢什么颜色呀？",
  "今天开心吗？",
  "你昨晚做了什么梦呀？",
  "你喜欢什么玩具呀？",
  "你最喜欢看什么动画片呀？",
  "你最想和哪种小动物做朋友呀？",
  "你喜欢下雪天还是晴天呀？",
  "你想去哪里玩呀？",
  "你最喜欢做什么事情呀？",
  "如果你有一个机器人小伙伴，你们会一起做什么呀？",
  "你最近学会了什么新本领呀？",
