// 获取阶段对应的输出格式要求
export function getStageFormatRequirements(stage: ConversationStage): string {
  switch(stage) {
    case 'A':
      return `
回复应包含:
1. 一个开放性但有引导性的问题
2. 对儿童回答的积极回应
3. 不超过3个简短句子
      `;
    
    case 'B':
      return `
回复应包含:
1. 对儿童兴趣的肯定
2. 1-2个引导性问题
3. 2-3个可能的创意方向
4. 简短句子，适合4-6岁儿童理解
      `;
    
    case 'C':
      return `
回复应包含:
1. 对儿童想法的肯定
2. 关于主角细节的1-2个引导性问题
3. 1-2个创意建议
4. 简短鼓励性语句
      `;
    
    case 'D':
      return `
回复应包含:
1. 对儿童想法的积极回应
2. 1-2个联想性问题
3. 1-2个可能的元素建议
4. 鼓励性语句
      `;
    
    case 'E':
      return `
回复应包含:
1. 对已有元素的肯定
2. 关于背景或辅助元素的1-2个问题
3. 1-2个细节建议
4. 简短鼓励性语句
      `;
    
    case 'F':
      return `
回复应包含:
1. 对整体创作的赞美
2. 对特定元素的具体肯定
3. 关于儿童感受的简单问题
4. 温暖的结束语
      `;
    
    default:
      return '';
  }
} 