// 获取阶段对应的输出格式要求
export function getStageFormatRequirements(stage: ConversationStage): string {
  switch(stage) {
    case 'A':
      return `
回复应包含:
1. 对儿童想法的积极回应
2. 1-2个引导性问题，帮助发展故事细节
3. 简短句子，适合4-6岁儿童理解
      `;
    
    case 'B1':
      return `
回复应包含:
1. 以"那么，我们就来画[主题]"的句式开头，总结要画的内容
2. 明确介绍主角，提出关于主角细节的1-2个具体引导性问题
3. 鼓励儿童发挥想象力，描述主角的特征
4. 简短句子，适合4-6岁儿童理解
      `;
    
    case 'B2':
      return `
回复应包含:
1. 对儿童描述的积极回应
2. 关于主角的1-2个新的细节引导性问题
3. 鼓励儿童发挥想象力，描述主角的更多特征
4. 简短句子，适合4-6岁儿童理解
      `;
    
    case 'C':
      return `
回复应包含:
1. 1个联想性问题
2. 1个可能的元素建议
      `;
    
    case 'D':
      return `
回复应包含:
1. 关于背景或辅助元素的1个问题或1个细节建议
      `;
    
    case 'E':
      return `
回复应包含:
1. 对整体创作的赞美
2. 对特定元素的具体肯定
3. 关于儿童感受的简单问题
4. 温暖的结束语
      `;
    
    default:
      return '';
  }
} 